def _norm(s: str) -> str:
    s = (s or "").strip().lower().replace("ё", "е")
    for ch in "«»\"'()·,.":
        s = s.replace(ch, " ")
    return " ".join(s.split())


def canonical_region(text: str) -> str:
    """Регион/город → канонический слаг. Неизвестное возвращаем как есть (само-совпадение)."""
    n = _norm(text)
    if not n:
        return ""
    return _ALIASES.get(n, n)


def _region_from_gps(lat, lng) -> str:
    try:
        la, ln = float(lat), float(lng)
    except (TypeError, ValueError):
        return ""
    for slug, (la0, la1, ln0, ln1) in _BBOX.items():
        if la0 <= la <= la1 and ln0 <= ln <= ln1:
            return slug
    return ""


def resolve_client_region(region: str = "", city: str = "", lat=None, lng=None) -> str:
    """Канонический регион клиента. Приоритет: region → city → GPS-bbox. '' если не определить."""
    for candidate in (region, city):
        slug = canonical_region(candidate)
        if slug:
            return slug
    return _region_from_gps(lat, lng)


def region_display(slug: str, fallback: str = "") -> str:
    """Красивое имя региона для подписи в приложении."""
    if not slug:
        return fallback
    return REGION_DISPLAY.get(slug, fallback or slug)
