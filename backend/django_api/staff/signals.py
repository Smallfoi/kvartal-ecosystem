"""Правило единственного владельца соблюдается при каждом сохранении (S-13)."""


def keep_single_owner(sender, instance, raw=False, **kwargs):
    """Чужой флаг суперпользователя снимаем, владельцу — возвращаем.

    При загрузке фикстур (`raw=True`) не вмешиваемся: таблица в этот момент
    заполняется частями, и «первым суперпользователем» мог бы оказаться не тот.
    Такой случай ловит проверка на каждом запросе и `mata_owner --repair`.
    """
    if raw:
        return
    from .owner import enforce

    try:
        enforce(instance)
    except Exception:      # правило не должно ронять сохранение записи
        pass
